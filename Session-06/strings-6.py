my_text = "HELLO world!"
print()

lowercase_text = my_text.lower()
print(lowercase_text)

uppercase_text = my_text.upper()
print(uppercase_text)

capitalised_text = my_text.capitalize()
print(capitalised_text)

centred_text = my_text.center(30)
print(centred_text)

centred_text_with_stars = my_text.center(20, "*")
print(centred_text_with_stars)

